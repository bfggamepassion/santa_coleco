"""Builds xmas.s: 'Jingle Bells' (refrain) for the ColecoVision BIOS sound engine.

Melody on tone channel 2, bass on tone channel 3 (the sound effects use tone 1, tone 3
and noise). Both voices last exactly the same number of frames and end with the BIOS
'repeat' code, so they loop forever in sync.
usage: python tools/make_music.py   (from the 'Save Christmas' folder)
"""
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLOCK = 3579545
Q = 24                      # noire = 24 images (150 bpm a 60 Hz)
GAP = 2                     # silence entre deux notes pour les detacher

NOTES = {'C': -9, 'D': -7, 'E': -5, 'F': -4, 'G': -2, 'A': 0, 'B': 2}
def period(name):           # 'E5', 'G3'...
    f = 440.0 * 2 ** ((NOTES[name[0]] + 12 * (int(name[1]) - 4)) / 12)
    n = round(CLOCK / (32 * f))
    assert 0 < n < 1024, name
    return n

# (note, duree en noires) ; '-' = silence
q, h, w, dq, e = 1, 2, 4, 1.5, 0.5
MELODY = [
    ('E5',q),('E5',q),('E5',h),        ('E5',q),('E5',q),('E5',h),
    ('E5',q),('G5',q),('C5',dq),('D5',e), ('E5',w),
    ('F5',q),('F5',q),('F5',dq),('F5',e), ('F5',q),('E5',q),('E5',q),('E5',e),('E5',e),
    ('E5',q),('D5',q),('D5',q),('E5',q), ('D5',h),('G5',h),
    ('E5',q),('E5',q),('E5',h),        ('E5',q),('E5',q),('E5',h),
    ('E5',q),('G5',q),('C5',dq),('D5',e), ('E5',w),
    ('F5',q),('F5',q),('F5',dq),('F5',e), ('F5',q),('E5',q),('E5',q),('E5',e),('E5',e),
    ('G5',q),('G5',q),('F5',q),('D5',q), ('C5',w),
]
ROOT = {'C': ('C3', 'G3'), 'F': ('F3', 'C4'), 'G': ('G3', 'D4'), 'D': ('D3', 'A3')}
CHORDS = 'C C C C F C D G C C C C F C G C'.split()
BASS = [(n, q) for c in CHORDS for n in ROOT[c] * 2]

def voice(notes, ch, atten):
    out = []
    for name, beats in notes:
        d = int(beats * Q)
        if name == '-':
            out.append((d, None)); continue
        n = period(name)
        out.append(('0x%02X,0x%02X,0x%02X,0x%02X' % (ch << 6, n & 0xFF, (atten << 4) | (n >> 8), d - GAP), name))
        out.append(('0x%02X' % ((ch << 6) | 0x20 | GAP), None))
    out.append(('0x%02X' % ((ch << 6) | 0x18), 'boucle'))
    return out

total = lambda notes: sum(int(b * Q) for _, b in notes)
assert total(MELODY) == total(BASS) == 16 * 4 * Q, (total(MELODY), total(BASS))

lines = ['; Generated by tools/make_music.py - do not edit',
         '; Jingle Bells (refrain) : melodie canal 2, basse canal 3', '',
         '\t.module xmas', '\t.globl _xmas_melody', '\t.globl _xmas_bass', '\t.area _CODE', '']
for label, notes, ch, att in (('_xmas_melody', MELODY, 2, 1), ('_xmas_bass', BASS, 3, 4)):
    lines.append(label + ':')
    for data, comment in voice(notes, ch, att):
        lines.append('\t.db ' + data + ('\t; ' + comment if comment else ''))
    lines.append('')
open(os.path.join(HERE, 'xmas.s'), 'w').write('\n'.join(lines))
print('loop', total(MELODY), 'frames')
