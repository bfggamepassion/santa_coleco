"""Builds scroll.c: pre-shifted characters for the scrolling scenery (pixel-smooth movement).

Every object is re-rendered shifted right by 0..7 pixels; the resulting 8x8 cells are
de-duplicated and stored as RLE pattern/colour data, plus one name frame per (object, shift).
All objects share one global sub-character phase, so a frame is just a put_frame().

  sky objects (star, ball)      -> screen third 0 (rows 0-7),   1 pixel steps, chars SKY_FIRST..
  ground objects (tree, snowman)-> screen third 2 (rows 16-23), 2 pixel steps, chars GND_FIRST..
Char 32 (white space) is the blank cell in both thirds.
usage: python tools/make_scroll.py   (from the 'Save Christmas' folder)
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tmslib import *

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
arr = read_arrays(os.path.join(HERE, 'charset.c'))
pat = rle_decode(arr['PATTERNRLE']); col = rle_decode(arr['COLORRLE'])

# order = SCROLLOBJ_ARBRE, _BONHOMME, _ETOILE, _BOULE (see charset.c)
OBJS = [('Arbre', 8, 8, 'GND'), ('Bonhomme', 6, 6, 'GND'), ('Etoile', 4, 3, 'SKY'), ('Boule', 4, 3, 'SKY')]
GROUPS = {'SKY': dict(first=91, last=255, step=1), 'GND': dict(first=33, last=255, step=2)}
BLANK = 32
WHITE = 15

def pixels(name, w, h):
    t = arr['scrollObj_' + name]
    im = [[WHITE] * (8 * w) for _ in range(8 * h)]
    for j in range(h):
        for i in range(w):
            c = t[j * w + i]
            for r in range(8):
                p, cl = pat[c * 8 + r], col[c * 8 + r]
                for b in range(8):
                    v = (cl >> 4) if p & (0x80 >> b) else (cl & 15)
                    im[j * 8 + r][i * 8 + b] = v or WHITE
    return im

out = ['/* Generated by tools/make_scroll.py - do not edit */', '#include <coleco.h>', '']
frames = {}
for g, cfg in GROUPS.items():
    cells = {}      # (8 pattern bytes, 8 colour bytes) -> char
    gpat, gcol = [], []
    for oi, (name, w, h, grp) in enumerate(OBJS):
        if grp != g: continue
        im = pixels(name, w, h)
        for phase in range(8):
            s = phase - phase % cfg['step']
            if s != phase:                       # coarser group: reuse previous frame
                frames[(oi, phase)] = frames[(oi, s)]; continue
            names = []
            for j in range(h):
                for i in range(w):
                    rows = [encode_row([im[j * 8 + r][x - s] if x - s >= 0 else WHITE
                                        for x in range(i * 8, i * 8 + 8)]) for r in range(8)]
                    if all(p == 0 and (c & 15) == WHITE for p, c in rows):
                        names.append(BLANK); continue
                    key = tuple(rows)
                    if key not in cells:
                        cells[key] = cfg['first'] + len(cells)
                        assert cells[key] != BLANK and cells[key] <= cfg['last'], (g, len(cells))
                        gpat += [p for p, c in rows]; gcol += [c for p, c in rows]
                    names.append(cells[key])
            fname = 'scrollFrame_%s_%d' % (name, phase)
            out.append('const byte %s[] = {%s};' % (fname, ','.join(map(str, names))))
            frames[(oi, phase)] = fname
    out.append('')
    out.append('const byte %s_FIRST = %d;' % (g, cfg['first']))
    out.append('const byte %s_COUNT = %d;' % (g, len(cells)))
    out.append(c_array(g + '_PATRLE', rle_encode(gpat)))
    out.append(c_array(g + '_COLRLE', rle_encode(gcol)))
    print(g, len(cells), 'chars,', len(rle_encode(gpat)) + len(rle_encode(gcol)), 'bytes RLE')

out.append('/* [object * 8 + phase], phase = pixel offset to the right inside the character */')
out.append('const byte* const scrollObj_Frames[] = {')
out.append(',\n'.join('  ' + ', '.join(frames[(oi, ph)] for ph in range(8)) for oi in range(len(OBJS))))
out.append('};')
open(os.path.join(HERE, 'scroll.c'), 'w').write('\n'.join(out) + '\n')
