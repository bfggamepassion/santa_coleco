"""Builds title.c (ColecoVision mode 2 title screen) from Ressources/title_native.png.

The picture was generated with ComfyUI (Krea 2, machine 'colecovision'); the title text is
drawn here with the game's own font, then every 8x1 cell is re-encoded to 2 colours.
usage: python tools/make_title.py   (from the 'Save Christmas' folder)
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tmslib import *
from PIL import Image

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
arr = read_arrays(os.path.join(HERE, 'charset.c'))
font = rle_decode(arr['PATTERNRLE'])

img = Image.open(os.path.join(HERE, 'Ressources', 'title_native.png')).convert('RGB')
W, H = 256, 192
scr = [[nearest(img.getpixel((x, y))) for x in range(W)] for y in range(H)]

def text(s, x0, y0, col, scale=1, shadow=None):
    passes = [(1, 1, shadow), (0, 0, col)] if shadow is not None else [(0, 0, col)]
    for ox, oy, c_ in passes:
        for n, ch in enumerate(s):
            c = ord(ch)
            for r in range(8):
                bits = font[c * 8 + r]
                for b in range(8):
                    if bits & (0x80 >> b):
                        for dy in range(scale):
                            for dx in range(scale):
                                x = x0 + (n * 8 + b) * scale + dx + ox
                                y = y0 + r * scale + dy + oy
                                if 0 <= x < W and 0 <= y < H: scr[y][x] = c_

def centered(s, y, col, scale=1, shadow=None):
    text(s, (W - len(s) * 8 * scale) // 2, y, col, scale, shadow)

def box(x0, y0, x1, y1, col):
    for y in range(y0, y1):
        for x in range(x0, x1): scr[y][x] = col

box(0, 0, W, 44, 1)                       # clean black sky band for the title
centered('SANTA MUST', 4, 8, 2, 6)
centered('SAVE XMAS', 24, 15, 2, 14)
box(0, 176, W, H, 1)
centered('PRESS FIRE', 180, 11)

pat = []; col = []
for band in range(3):
    for cy in range(8):
        for cx in range(32):
            for r in range(8):
                y = band * 64 + cy * 8 + r
                p, c = encode_row(scr[y][cx * 8:cx * 8 + 8])
                pat.append(p); col.append(c)

# preview of what the VDP will show
prev = Image.new('RGB', (W, H))
for i in range(6144):
    band, rest = divmod(i, 2048); cell, r = divmod(rest, 8)
    cy, cx = divmod(cell, 32)
    for b in range(8):
        c = (col[i] >> 4) if pat[i] & (0x80 >> b) else (col[i] & 15)
        prev.putpixel((cx * 8 + b, band * 64 + cy * 8 + r), PAL[c])
prev.save(os.path.join(HERE, 'Ressources', 'title_preview.png'))

rp, rc = rle_encode(pat), rle_encode(col)
with open(os.path.join(HERE, 'title.c'), 'w') as f:
    f.write('/* Generated by tools/make_title.py - do not edit */\n#include <coleco.h>\n\n')
    f.write(c_array('TITLE_PATRLE', rp)); f.write('\n'); f.write(c_array('TITLE_COLRLE', rc))
print('pattern RLE', len(rp), 'colour RLE', len(rc), 'total', len(rp) + len(rc))
